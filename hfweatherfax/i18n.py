def tr(language: str, key: str, **kwargs) -> str:
    lang = language if language in TRANSLATIONS else "en"
    template = TRANSLATIONS[lang].get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
